#!/usr/bin/env python3
"""
OSC Preview

What a receiver sees on the wire for a given output format and tracking mode,
generated by running a fake frame through the real OscEmitter into a capturing
sender - so the address map and payload sample in the settings, and the Live
pane's address list, can never drift from the formatters in osc_protocol.py.

Qt-free; imports of the OSC stack are deferred to first use.

Public API:
    addresses(protocol, mode, num_poses=1) -> [(address, payload_desc, rate_hint)]
    payload_sample(protocol, mode) -> (text, note)
    capture(protocol, mode) -> [(address, args)]   # every message of a frame, a clear and a heartbeat
"""

# ============================================================================
# IMPORTS
# ============================================================================
from __future__ import annotations

import json
import re
from typing import Any, List, Tuple

# ============================================================================
# CONSTANTS
# ============================================================================
MODES = ('pose', 'hand', 'all')
RATE_FRAME = 'per frame'
RATE_HEARTBEAT = '1 / s'
_SAMPLE_TS = 1724803912.418
_JSON_SAMPLE_CHARS = 170
_FLOAT_SAMPLE_LINES = 3

_LM_ADDRESS = re.compile(r'^(.*/lm)/\d+$')


# ============================================================================
# FAKE DATA
# ============================================================================
class _Landmark:
    """A landmark with the attributes the formatters read."""

    def __init__(self, x, y, z, visibility=None):
        self.x, self.y, self.z = x, y, z
        if visibility is not None:
            self.visibility = visibility


def _landmarks(count: int, visibility: bool, spread: float = 0.5) -> list:
    out = []
    for n in range(count):
        t = n / max(1, count - 1)
        out.append(_Landmark(round(0.5 + (t - 0.5) * spread, 3), round(0.15 + t * 0.7, 3),
                             round(-0.3 + t * 0.2, 3), 0.99 if visibility else None))
    return out


class _CapturingSender:
    """Stands in for ThreadedOSCSender: decodes every packet it is handed."""

    def __init__(self):
        self.messages: list[tuple[str, list]] = []

    def send_packet(self, data) -> None:
        from pythonosc.osc_bundle import OscBundle
        from pythonosc.osc_message import OscMessage

        raw = bytes(data.dgram if hasattr(data, 'dgram') else data)
        if raw.startswith(b'#bundle'):
            for content in OscBundle(raw):
                self._add(content)
        else:
            self._add(OscMessage(raw))

    def _add(self, content) -> None:
        if hasattr(content, 'address'):
            self.messages.append((content.address, list(content.params)))
        else:  # nested bundle
            for inner in content:
                self._add(inner)

    def get_stats(self) -> dict:
        return {'queued': 0, 'dropped': 0, 'sent': len(self.messages)}


# ============================================================================
# CAPTURE
# ============================================================================
def capture(protocol: str, mode: str, num_poses: int = 1) -> List[Tuple[str, list]]:
    """
    Run one tracked frame, one lost-tracking frame and a heartbeat through the
    real OscEmitter.

    Args:
        protocol: legacy, json or float.
        mode: pose, hand or all.
        num_poses: Poses in the fake frame (the float format addresses poses
            after the first as /pose/<n>/...).

    Returns:
        (address, args) for every message, in send order, bundles unpacked.
    """
    from .osc_protocol import OscEmitter

    sender = _CapturingSender()
    emitter = OscEmitter(sender, protocol)
    pose = mode in ('pose', 'all')
    hand = mode in ('hand', 'all')

    emitter.begin_frame(_SAMPLE_TS)
    if pose:
        for person in range(max(1, int(num_poses))):
            emitter.pose(person, _landmarks(33, True), _landmarks(33, False, 0.4), None,
                         'pose' if person == 0 else f'pose_{person}', ts=_SAMPLE_TS)
        emitter.pose_status(max(1, int(num_poses)))
    if hand:
        for label in ('Left', 'Right'):
            emitter.hand(label, _landmarks(21, False, 0.2), _landmarks(21, False, 0.1), None,
                         'hand_left' if label == 'Left' else 'hand_right', ts=_SAMPLE_TS)
        emitter.hand_status(2)
    emitter.end_frame()

    emitter.begin_frame(_SAMPLE_TS + 0.033)
    if pose:
        emitter.pose_cleared(ts=_SAMPLE_TS + 0.033)
        emitter.pose_status(0)
    if hand:
        emitter.hand_cleared('Left', ts=_SAMPLE_TS + 0.033)
        emitter.hand_cleared('Right', ts=_SAMPLE_TS + 0.033)
        emitter.hand_status(0)
    emitter.end_frame()

    emitter.heartbeat(fps=30.0)
    return sender.messages


# ============================================================================
# ADDRESS MAP
# ============================================================================
def _json_shape(text: str) -> str:
    """`{timestamp, landmarks[33]}` for a JSON payload."""
    try:
        data = json.loads(text)
    except ValueError:
        return 'string'
    if not isinstance(data, dict):
        return 'JSON'
    if not data:
        return 'JSON {} (cleared)'
    if all(k == 'person' or k.startswith(('min_', 'max_')) for k in data):
        return 'JSON bounds (min/max x y z)'
    parts = [f'{k}[{len(v)}]' if isinstance(v, list) else k for k, v in data.items()]
    return 'JSON {' + ', '.join(parts) + '}'


def _describe(address: str, args: list, count: int = 1) -> str:
    """Human description of one message's arguments (count > 1: a landmark family)."""
    if len(args) == 1 and isinstance(args[0], str):
        return _json_shape(args[0])
    if address.endswith('/heartbeat'):
        return 'fps, queued, dropped, sent'
    if address.endswith(('/status', '/tracking')):
        return 'count (int)'
    if address.endswith('bounds'):
        return '6 floats (min/max x y z)'
    if count > 1 or address.endswith('/lm/*'):
        fields = 'x y z visibility' if len(args) == 4 else 'x y z'
        return f'{count} × {fields} (float)'
    return ' '.join(type(a).__name__ for a in args)


def addresses(protocol: str, mode: str, num_poses: int = 1) -> List[Tuple[str, str, str]]:
    """
    The address map a receiver can expect.

    Args:
        protocol: legacy, json or float.
        mode: pose, hand or all.
        num_poses: Poses tracked; with float and more than one, the
            /pose/<n>/lm/* family for later poses is listed too.

    Returns:
        (address, payload_desc, rate_hint) rows, each address once and in
        send order: data, status, tracking, then the heartbeat. Per-landmark
        float families are grouped as `/pose/lm/*` with the landmark count in
        the description.
    """
    rows: dict[str, dict[str, Any]] = {}
    for address, args in capture(protocol, mode, num_poses):
        grouped = _LM_ADDRESS.sub(r'\1/*', address)
        # /pose/1/lm/3 -> /pose/<n>/lm/*
        grouped = re.sub(r'^/pose/[1-9]\d*/', '/pose/<n>/', grouped)
        row = rows.setdefault(grouped, {'args': args, 'members': set()})
        row['members'].add(address)
    out = []
    for address, row in rows.items():
        count = len(row['members']) if address.endswith('/lm/*') else 1
        rate = RATE_HEARTBEAT if address.endswith('/heartbeat') else RATE_FRAME
        out.append((address, _describe(address, row['args'], count), rate))
    return out


# ============================================================================
# PAYLOAD SAMPLE
# ============================================================================
def _format_arg(arg) -> str:
    if isinstance(arg, float):
        return f'{arg:.3f}'
    return str(arg)


def payload_sample(protocol: str, mode: str) -> Tuple[str, str]:
    """
    A sample of the first data message the active formatter sends.

    Args:
        protocol: legacy, json or float.
        mode: pose, hand or all (hand mode samples a hand).

    Returns:
        (text, note): the sample as a receiver would see it, and a one-line
        note on its shape.
    """
    messages = capture(protocol, 'hand' if mode == 'hand' else 'pose')
    if protocol == 'float':
        lm = [(a, args) for a, args in messages if _LM_ADDRESS.match(a)]
        lines = [f'{a} ' + ' '.join(_format_arg(v) for v in args) for a, args in lm[:_FLOAT_SAMPLE_LINES]]
        lines.append('…')
        return '\n'.join(lines), 'One message per landmark, plain floats; bounds are six floats'
    address, args = next(((a, x) for a, x in messages if x and isinstance(x[0], str) and '"landmarks"' in x[0]),
                         (messages[0][0], messages[0][1]))
    body = args[0]
    if len(body) > _JSON_SAMPLE_CHARS:
        body = body[:_JSON_SAMPLE_CHARS].rstrip(',') + ' …'
    note = 'One JSON string argument'
    if protocol == 'json':
        note += '; the array index is the landmark id'
    return f'{address} {json.dumps(body)}', note
